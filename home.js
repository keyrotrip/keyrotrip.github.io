  const 최고 = 안매긴.reduce((m, c) => Math.min(m, 유명도(c)), 9);
  const 유명한것 = 안매긴.filter(c => 유명도(c) === 최고).sort(나머지순);
  let 목록 = [...매긴, ...유명한것].slice(0, 12);
