/* ── 경로 하나를 고리들로 (b696 에 `읽기` 에서 떼어냈습니다) ───────────
   ⚠ **50m 나라 파일(map50/XX.js)도 «같은 문법·같은 좌표계»입니다.** 그래서
     이 함수 하나로 둘 다 읽습니다 — 나라 화면에 들어갈 때 그 나라만 자세한
     윤곽으로 바꿔 그립니다(`자세히`). */
function 고리읽기(d){
  {
    const 고리 = [];
    let 지금 = null, x = 0, y = 0;
    /* M 은 절대, l 은 상대입니다(world.js 가 그렇게 저장돼 있습니다).
       ⚠ 다른 명령이 섞이면 여기서 조용히 틀립니다 — 자료를 바꾸면
         `M=… Z=… l=…` 만 쓰는지 먼저 세십시오. */
    for (const 토막 of d.split(/(?=[MmLlZz])/)){
      const op = 토막[0];
      if (!op) continue;
      const n = (토막.match(/-?\d*\.?\d+/g) || []).map(Number);
      if (op === 'M' || op === 'm'){
        if (지금 && 지금.length > 2) 고리.push(지금);
        지금 = [];
        if (op === 'M'){ x = n[0]; y = n[1]; } else { x += n[0]; y += n[1]; }
        지금.push(점(x, y));
        for (let i = 2; i + 1 < n.length; i += 2){
          if (op === 'M'){ x = n[i]; y = n[i + 1]; } else { x += n[i]; y += n[i + 1]; }
          지금.push(점(x, y));
        }
      } else if (op === 'l' || op === 'L'){
        for (let i = 0; i + 1 < n.length; i += 2){
          if (op === 'l'){ x += n[i]; y += n[i + 1]; } else { x = n[i]; y = n[i + 1]; }
          지금.push(점(x, y));
        }
      } else if (op === 'Z' || op === 'z'){
        if (지금 && 지금.length > 2) 고리.push(지금);
        지금 = null;
      }
    }
    if (지금 && 지금.length > 2) 고리.push(지금);
    return 고리;
  }
}

