/* ── 경로 문자열 → 조각 ───────────────────────────────────────────────
   ⚠ map50 은 「M x y l dx dy …Z」 꼴입니다(상대 좌표). 절대로 풀어 담습니다.
   ⚠ 조각마다 상자를 같이 잽니다 — 화면 밖 조각을 건너뛸 때 씁니다. */
export function 조각내기(d){
  const 조각 = [];
  if (!d) return 조각;
  for (const s of String(d).matchAll(/M\s*(-?[\d.]+)[\s,]+(-?[\d.]+)([^M]*)/g)){
    let x = +s[1], y = +s[2];
    const 점 = [[x, y]];
    let x0 = x, x1 = x, y0 = y, y1 = y;
    const 수 = s[3].match(/-?\d*\.?\d+/g) || [];
    for (let i = 0; i + 1 < 수.length; i += 2){
      x += +수[i]; y += +수[i + 1];
      점.push([x, y]);
      if (x < x0) x0 = x; if (x > x1) x1 = x;
      if (y < y0) y0 = y; if (y > y1) y1 = y;
    }
    조각.push({ 점, x0, x1, y0, y1 });
  }
  return 조각;
}

/* ── 못 받은 까닭을 남깁니다(b796) ─────────────────────────────────────
 * ⚠⚠ 전에는 조용히 `null` 로만 뒀습니다. b795 에 폰에서 지도 자료가 통째로 안 와서 온
 *   유럽이 앱 초기 칠로 돌아갔는데 **오류 기록이 0 건**이라 까닭을 짐작밖에 못 했습니다.
 *   이제 오류 기록(client_errors)에 남깁니다 — `reportError` 는 app.js 의 'error' 받이로 갑니다.
 * ⚠ **없는 파일(404)은 안 남깁니다.** 그건 「받아봤는데 없더라」(투발루의 map50, 시·군 자료가
 *   없는 나라의 adm2)라 원래 있는 일입니다. import 의 오류로는 둘을 못 가르므로 한 번 더
 *   받아 봅니다 — 실패했을 때만이라 드뭅니다. 저장 공간 수치도 붙입니다(가득 찼나를 재려고). */
function 못받음(주소, err){
  (async () => {
    let 다시 = '';
    try {
      const r = await fetch(주소);
      if (r.status === 404) return;
      다시 = ` · 다시 받으니 ${r.status}`;
    } catch (e2){ 다시 = ` · 다시 받아도 실패(${e2?.message || e2})`; }
    let 용량 = '';
    try {
      const s = await navigator.storage?.estimate?.();
      if (s) 용량 = ` · 저장 ${Math.round(s.usage / 1e6)}/${Math.round(s.quota / 1e6)}MB`;
    } catch {}
    self.reportError?.(new Error(`지도 자료 못 받음: ${주소.replace('./', '')} — ${err?.message || err}${다시}${용량}`));
  })();
}

