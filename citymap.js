/* ── 점이 고리 «안»에 있나 — 광선 쏘기 ───────────────────────────────
   ⚠ 한 단위가 고리 여럿일 수 있고 그중에는 **구멍**도 있습니다(서울은
     경기도 안에 뚫린 구멍입니다). 고리마다 따로 보면 서울 점이 경기도
     바깥고리에도 들어가 **둘 다 켜집니다** — 실제로 그렇게 나왔습니다.
     짝수-홀수로 세면 구멍이 저절로 처리됩니다. */
function 안에있나(x, y, 고리들){
  let 안 = false;
  for (const r of 고리들){
    const pt = r.점; const n = pt.length;
    for (let i = 0, j = n - 1; i < n; j = i++){
      const [xi, yi] = pt[i], [xj, yj] = pt[j];
      if ((yi > y) !== (yj > y) &&
          x < (xj - xi) * (y - yi) / ((yj - yi) || 1e-12) + xi) 안 = !안;
    }
  }
  return 안;
}

